#!/usr/bin/env python3
"""Generate Linux build inputs without writing into the upstream source tree."""

import pathlib
import re
import sys


def write_if_changed(path, content):
    if not path.exists() or path.read_text() != content:
        path.write_text(content)


def main():
    root = pathlib.Path(__file__).resolve().parents[2]
    output = pathlib.Path(sys.argv[1])
    output.mkdir(parents=True, exist_ok=True)
    versions = (
        ("NPP_SCINTILLA_VERSION", "scintilla/win32/ScintRes.rc", "VERSION_SCINTILLA"),
        ("NPP_LEXILLA_VERSION", "lexilla/src/LexillaVersion.rc", "VERSION_LEXILLA"),
        ("NPP_BOOST_REGEX_VERSION", "boostregex/boost/version.hpp", "BOOST_LIB_VERSION"),
    )
    lines = ["// Generated by PowerEditor/linux/prepare.py.\n"]
    for name, source, macro in versions:
        match = re.search(
            rf'^\s*#define\s+{macro}\s+("[^"]+")',
            (root / source).read_text(),
            re.MULTILINE,
        )
        if match is None:
            raise ValueError(f"Cannot find {macro} in {source}")
        lines.append(f"#define {name} {match[1]}\n")
    write_if_changed(output / "NppLibsVersion.h", "".join(lines))

if __name__ == "__main__":
    main()
